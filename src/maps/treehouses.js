import { DAY } from './env.js';

// Домики на деревьях. Карта симметрична поворотом на 180° вокруг центра: половина команды 0 (z < 0)
// строится функцией half(), вторая половина — та же функция с s = −1 (x → −x, z → −z).
// Высоты: земля 0, все площадки и мостики на 3.2 м, кроны начинаются на 5.6 м (крыши домиков).
// Линии: левый фланг (своя сторона) — мост от базы к дереву T1 и дальше длинный мост B2 к дереву
// у вражеской базы; правый фланг — земля под чужим мостом, домик на земле у забора; центр — земля
// с камнями, кустами, ящиками и площадкой между двумя деревьями, соединённой мостками с обоими флангами.

const H = 6.6; // верх забора (по штакетинам): выше любой доступной поверхности у края (перила 4.1 м) на 2.3+ м
const BASE = 4.6; // сплошная часть забора; выше — штакетины с щелями уже плеч игрока
const TOP = 3.2; // уровень площадок и мостов
const CROWN = TOP + 2.4; // низ кроны = крыша домика на дереве
const FLIP = { '+x': '-x', '-x': '+x', '+z': '-z', '-z': '+z' };

// Обёртка над MapBuilder для одной половины: s = 1 — как написано, s = −1 — повёрнуто на 180°.
function side(b, s) {
  const S = {
    box: (x, y, z, w, h, d, mat, o) => b.box(s * x, y, s * z, w, h, d, mat, o),
    stairs: (x, z, dir, width, height, steps, mat = 'wood', y0 = 0) => b.stairs(s * x, s * z, s > 0 ? dir : FLIP[dir], width, height, steps, mat, y0),
    crate: (x, y, z, size) => b.crate(s * x, y, s * z, size),
    noAccess: (x0, z0, x1, z1, minY) => b.noAccess(s * x0, s * z0, s * x1, s * z1, minY),
    pickup: (x, y, z) => b.pickup(s * x, y, s * z),
    // a — поворот взгляда от «прямо на врага» (к +x у команды 0).
    spawn: (x, z, a = 0) => b.spawn(s * x, 0, s * z, s > 0 ? 0 : 1, s > 0 ? Math.PI + a : a),
    // Стена с проёмами: при повороте отрезок [from, to] и проёмы отражаются по длине.
    wall: (axis, from, to, at, y, height, thick, mat, openings = []) => {
      if (s > 0) return b.wall(axis, from, to, at, y, height, thick, mat, openings);
      const len = to - from;
      return b.wall(axis, -to, -from, -at, y, height, thick, mat, openings.map((o) => ({ ...o, a: len - o.b, b: len - o.a })));
    },
  };
  // Дощатый настил площадки: верх на уровне top.
  S.deck = (x0, x1, z0, z1, top = TOP, th = 0.3) => S.box((x0 + x1) / 2, top - th, (z0 + z1) / 2, x1 - x0, th, z1 - z0, 'wood');
  // Опора из бревна под настилом.
  S.post = (x, z, top = TOP, w = 0.5) => S.box(x, 0, z, w, top - 0.3, w, 'log');
  // Перила: сплошной дощатый борт 0.9 м (укрытие сидя) вдоль X или Z.
  S.railX = (x0, x1, z, top = TOP) => { if (x1 - x0 > 0.05) S.box((x0 + x1) / 2, top, z, x1 - x0, 0.9, 0.12, 'wood'); };
  S.railZ = (z0, z1, x, top = TOP) => { if (z1 - z0 > 0.05) S.box(x, top, (z0 + z1) / 2, 0.12, 0.9, z1 - z0, 'wood'); };
  // Крона из слоёв листвы; нижний слой — крыша домика. Центр сдвигается, чтобы не вылезать за забор.
  S.crown = (x, z, size, y0 = CROWN) => {
    const cx = Math.max(-12 + size / 2, Math.min(12 - size / 2, x));
    const cz = Math.max(-24 + size / 2, Math.min(24 - size / 2, z));
    // Ступенчатые «кресты» из листвы дают округлую блочную крону.
    const layer = (y, h, a, c) => {
      S.box(cx, y, cz, a, h, c, 'leaves');
      if (a !== c) S.box(cx, y, cz, c, h, a, 'leaves');
    };
    layer(y0, 0.8, size, size - 1.8);
    layer(y0 + 0.8, 1.2, size, size - 0.8);
    layer(y0 + 2.0, 0.8, size - 1.4, size - 2.8);
    layer(y0 + 2.8, 0.6, size - 3.2, size - 3.2);
    // Верх кроны — не место для игрока: туда не допрыгнуть ни с площадки, ни с перил.
    S.noAccess(cx - size / 2, cz - size / 2, cx + size / 2, cz + size / 2, y0 + 0.5);
  };
  // Кусты и камни — укрытия по пояс/грудь, на них можно запрыгнуть.
  S.bush = (x, z, w, d, h = 1.3) => {
    S.box(x, 0, z, w, h, d, 'leaves');
    if (w > 1.6 && d > 1.2) S.box(x + 0.15, h, z - 0.1, w - 0.9, 0.45, d - 0.7, 'leaves');
  };
  S.rock = (x, z, w, d, h) => {
    S.box(x, 0, z, w, h, d, 'stone');
    S.box(x + 0.2, h, z - 0.15, w * 0.55, h * 0.4, d * 0.6, 'stone');
  };
  return S;
}

// Домик вокруг ствола на площадке: стены от пола до кроны, дверь и окна.
function hut(S, x0, x1, z0, z1, doors) {
  const h = CROWN - TOP;
  const t = 0.15;
  const win = (a, b) => ({ a, b, bottom: 1.0, top: 1.7 });
  const door = (a, b) => ({ a, b, bottom: 0, top: 2.05 });
  for (const [axis, from, to, at, key] of [['x', x0, x1, z0 + t / 2, '-z'], ['x', x0, x1, z1 - t / 2, '+z'], ['z', z0 + t, z1 - t, x0 + t / 2, '-x'], ['z', z0 + t, z1 - t, x1 - t / 2, '+x']]) {
    const spec = doors[key];
    if (spec === null) continue;
    const len = to - from;
    const openings = spec === 'door' ? [door(len / 2 - 0.6, len / 2 + 0.6)] : spec === 'win' ? [win(len / 2 - 0.7, len / 2 + 0.7)] : [];
    S.wall(axis, from, to, at, TOP, h, t, 'wood', openings);
  }
}

function half(b, s) {
  const S = side(b, s);

  // ---------- База: большая площадка над спавном на толстых бревенчатых опорах ----------
  S.deck(-12, 12, -24, -18);
  // Передняя стена под площадкой закрывает спавн от взглядов с поля; выходы — по бокам.
  S.box(0, 0, -18.15, 10.8, TOP - 0.3, 0.3, 'wood');
  // Дощатые заборы перед боковыми выходами: прикрывают крайние спавны.
  S.box(-6.0, 0, -15.3, 2.8, 2.4, 0.2, 'wood');
  S.box(6.0, 0, -15.3, 2.8, 2.4, 0.2, 'wood');
  for (const x of [-10.4, 10.4]) S.post(x, -17.9, TOP, 0.7);
  for (const x of [-8.6, -4.2, 4.2, 8.6]) S.post(x, -23.6, TOP, 0.6);
  // Лестницы на площадку у забора.
  S.stairs(-11.3, -14.85, '-z', 1.4, TOP, 7);
  S.stairs(11.3, -14.85, '-z', 1.4, TOP, 7);
  // Перила по переднему краю (с разрывами под мост B1 и лестницы).
  S.railX(-10.4, -7.6, -18.06);
  S.railX(-6.2, 10.4, -18.06);
  // Дерево базы: ствол сквозь площадку, домик со входом спереди, крона над ним.
  S.box(0, 0, -22.3, 1.6, CROWN + 1.5, 1.6, 'log');
  hut(S, -2.6, 2.6, -24, -20.4, { '-z': null, '+z': 'door', '-x': 'win', '+x': 'win' });
  S.crown(0, -21.8, 6.4);
  // Спавны под площадкой.
  for (const [x, z, a] of [[-6, -21.6, -0.5], [-2.6, -20.6, 0], [2.6, -20.6, 0], [6, -21.6, 0.5]]) S.spawn(x, z, a);
  S.crate(-10.9, 0, -23.2, 0.9);
  S.crate(10.9, 0, -23.2, 0.9);
  S.crate(-10.8, 0, -22.2, 0.6);
  // Ящики на площадке базы — укрытие для стрельбы сверху.
  S.crate(-4.6, TOP, -19.3, 1.0);
  S.crate(5.4, TOP, -19.5, 0.9);

  // ---------- Мост B1: от базы к дереву T1 (левый фланг) ----------
  S.deck(-7.6, -6.2, -18, -11.8, TOP, 0.2);
  S.railZ(-18, -11.8, -7.54);
  S.railZ(-18, -11.8, -6.26);
  S.post(-6.9, -15.3, TOP, 0.45);

  // ---------- Дерево T1: площадка, домик вокруг ствола ----------
  S.deck(-12, -4.6, -11.8, -6.2);
  for (const [x, z] of [[-11.6, -11.4], [-4.9, -11.5], [-4.9, -6.5], [-11.6, -6.6]]) S.post(x, z);
  S.box(-10.6, 0, -9, 1.3, CROWN + 1.5, 1.3, 'log');
  hut(S, -12, -7.9, -11, -7, { '-z': 'win', '+z': 'win', '-x': null, '+x': 'door' });
  S.crown(-10, -9, 5.4);
  S.railX(-6.2, -4.6, -11.74);
  S.railX(-6.2, -4.6, -6.26);
  S.railZ(-11.8, -10.75, -4.66);
  S.railZ(-9.25, -6.2, -4.66);
  // Лестница с центральной дорожки на T1.
  S.stairs(-1.5, -10, '-x', 1.4, TOP, 7);
  S.pickup(-5.6, TOP, -11.1);

  // ---------- Мост B2: от T1 вдоль фланга через середину к дереву у чужой базы ----------
  S.deck(-7.6, -6.2, -6.2, 6.2, TOP, 0.2);
  S.railZ(-6.2, 6.2, -7.54);
  S.railZ(-6.2, -0.7, -6.26);
  S.railZ(0.7, 6.2, -6.26);
  S.post(-6.9, -3.4, TOP, 0.45);
  S.post(-6.9, 3.4, TOP, 0.45);
  // Поперечный мостик к центральному дереву.
  S.deck(-6.2, -3.6, -0.7, 0.7, TOP, 0.2);
  S.railX(-6.2, -3.6, -0.64);
  S.railX(-6.2, -3.6, 0.64);

  // ---------- Дерево T2 (правый фланг): площадка с домиком, сюда приходит чужой мост ----------
  S.deck(4.6, 12, -11.8, -6.2);
  for (const [x, z] of [[11.6, -11.4], [4.9, -11.5], [4.9, -6.5], [11.6, -6.6]]) S.post(x, z);
  S.box(10.6, 0, -9, 1.3, CROWN + 1.5, 1.3, 'log');
  hut(S, 7.9, 12, -11, -7, { '-z': 'win', '+z': 'win', '-x': 'door', '+x': null });
  S.crown(10, -9, 5.4);
  S.railX(6.0, 7.9, -11.74);
  S.railX(4.6, 6.2, -6.26);
  S.railZ(-11.8, -6.2, 4.66);
  // Лестница с земли на T2 со стороны базы.
  S.stairs(5.3, -14.95, '+z', 1.4, TOP, 7);

  // ---------- Центральная лестница на площадку центрального дерева ----------
  S.stairs(-2.2, -5.95, '+z', 1.4, TOP, 7);

  // ---------- Домик на земле у забора (правый фланг): двери вдоль фланга, окно к центру ----------
  {
    const [x0, x1, z0, z1] = [8.6, 11.6, -4.8, -1.6];
    const t = 0.2;
    const h = 2.4;
    S.wall('x', x0, x1, z0 + t / 2, 0, h, t, 'wood', [{ a: 0.9, b: 2.1, bottom: 0, top: 2.05 }]);
    S.wall('x', x0, x1, z1 - t / 2, 0, h, t, 'wood', [{ a: 0.9, b: 2.1, bottom: 0, top: 2.05 }]);
    S.wall('z', z0 + t, z1 - t, x0 + t / 2, 0, h, t, 'wood', [{ a: 0.6, b: 2.0, bottom: 1.0, top: 1.7 }]);
    S.wall('z', z0 + t, z1 - t, x1 - t / 2, 0, h, t, 'wood');
    S.box((x0 + x1) / 2, h, (z0 + z1) / 2, x1 - x0 + 0.4, 0.2, z1 - z0 + 0.4, 'wood');
    S.box((x0 + x1) / 2, h + 0.2, (z0 + z1) / 2, x1 - x0 - 0.6, 0.35, z1 - z0 - 0.6, 'wood');
    S.crate(8.1, 0, -5.4, 1.0);
    S.pickup(10.1, 0, -3.2);
  }

  // ---------- Укрытия на земле ----------
  S.bush(-1.2, -15.2, 2.6, 1.4);
  S.rock(3.2, -14.2, 1.8, 1.4, 1.0);
  S.bush(-9.4, -13.3, 1.6, 1.4, 1.2);
  S.bush(8.2, -13.6, 1.8, 1.2, 1.2);
  S.box(-2.8, 0, -12.6, 3.2, 0.7, 0.7, 'log'); // поваленное бревно
  S.crate(1.6, 0, -11.0, 1.2);
  S.crate(2.3, 0, -9.9, 0.9);
  S.rock(-9.6, -2.6, 1.6, 1.8, 1.1);
  S.bush(-10.4, 6.0, 1.4, 1.6, 1.2);
  S.rock(3.0, -6.2, 1.6, 1.4, 1.0);
  S.rock(-4.6, -4.0, 1.2, 1.2, 0.8);
  S.crate(5.8, 0, -1.8, 1.1);
  S.bush(3.0, -8.2, 1.2, 1.4, 1.1);
  S.bush(-11.1, -4.8, 1.4, 1.4, 1.1);
  S.bush(11.2, 1.6, 1.2, 1.4, 1.0);
}

export default {
  id: 'treehouses',
  name: 'Домики на деревьях',
  desc: 'Домики на деревьях, мостики между ними и забор вокруг.',
  size: [24, 48],
  seed: 505,
  env: { ...DAY, azimuth: 125, elevation: 52 },
  build(b) {
    b.arena(24, 48, { wall: 'wood', ground: 'sand', height: BASE });
    // Штакетины поверх забора: щели 0.3 м — встать между ними нельзя, верх на H.
    const pick = (x, z, w, d) => b.box(x, BASE, z, w, H - BASE, d, 'wood');
    for (let x = -12.6; x < 12.6; x += 0.8) {
      pick(x + 0.25, -24.5, 0.5, 1);
      pick(-x - 0.25, 24.5, 0.5, 1);
    }
    for (let z = -23.6; z < 23.6; z += 0.8) {
      pick(-12.5, z + 0.25, 1, 0.5);
      pick(12.5, -z - 0.25, 1, 0.5);
    }
    // Столбы забора с внутренней стороны.
    for (let z = -20; z <= 20; z += 5) {
      b.box(-11.88, 0, z, 0.24, H, 0.5, 'log');
      b.box(11.88, 0, -z, 0.24, H, 0.5, 'log');
    }
    // Центр: общая площадка между двумя деревьями (стволы смещены от центра, чтобы не закрывать
    // симметричные линии обзора через середину). К ней ведут поперечные мостки и две лестницы.
    b.box(0, TOP - 0.3, 0, 7.2, 0.3, 5.6, 'wood');
    for (const s of [1, -1]) {
      const S = side(b, s);
      S.box(2.4, 0, -1.6, 1.2, CROWN + 1.5, 1.2, 'log');
      S.crown(2.4, -1.6, 4.8);
      S.post(-3.3, -2.5);
      S.railX(-3.6, -2.9, -2.74);
      S.railX(-1.5, 3.6, -2.74);
      S.railZ(-2.8, -0.7, 3.54);
      S.railZ(0.7, 2.8, 3.54);
    }
    for (const s of [1, -1]) half(b, s);
  },
};
